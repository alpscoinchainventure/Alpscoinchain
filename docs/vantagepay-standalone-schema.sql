CREATE OR REPLACE FUNCTION public.vp_notify_transaction_request()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_title TEXT;
  v_message TEXT;
  v_type TEXT;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_type := CASE WHEN NEW.request_type = 'deposit' THEN 'deposit_request' ELSE 'withdrawal_request' END;
    v_title := CASE WHEN NEW.request_type = 'deposit' THEN 'Deposit request received' ELSE 'Withdrawal request received' END;
    v_message := 'Your ' || NEW.request_type || ' request ' || NEW.request_reference || ' was received and is pending review. No money has been moved.';
    INSERT INTO public.vp_customer_notifications(user_id, notification_type, title, message, related_request_id)
    VALUES (NEW.user_id, v_type, v_title, v_message, NEW.id);
    RETURN NEW;
  END IF;

  IF NEW.status IS DISTINCT FROM OLD.status THEN
    v_title := 'Transaction request update';
    v_message := 'Your ' || NEW.request_type || ' request ' || NEW.request_reference || ' status changed to ' || NEW.status || '. Check your VantagePay dashboard for details.';
    INSERT INTO public.vp_customer_notifications(user_id, notification_type, title, message, related_request_id)
    VALUES (NEW.user_id, 'request_status', v_title, v_message, NEW.id);
  END IF;
  RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.vp_notify_transaction_request() FROM PUBLIC, anon, authenticated;
